package com.lowenhert.patchmanagement.core.testlibrary;

import java.util.List;
import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Generates pytest / Robot Framework code from test case events with fixed templates. The LLM never writes code;
 * every value coming from plans, OCR or users is escaped for the target language.
 */
public final class ScriptCodeGenerator {

    static final double KEY_SETTLE_SECONDS = 1.0;
    private static final Pattern CONTROL = Pattern.compile("[\\p{Cntrl}]");
    private static final Pattern NON_IDENTIFIER = Pattern.compile("[^a-z0-9]+");
    private static final Pattern ROBOT_NAME_UNSAFE = Pattern.compile("[^\\p{L}\\p{N} _.,()-]+");

    private ScriptCodeGenerator() {
    }

    public static String generate(TestScript.Language language, String name, String description, List<TestCaseEvent> events) {
        return language == TestScript.Language.PYTEST ? pytest(name, description, events) : robot(name, description, events);
    }

    // ── pytest ──────────────────────────────────────────────────────────────

    static String pytest(String name, String description, List<TestCaseEvent> events) {
        StringBuilder sb = new StringBuilder();
        sb.append("\"\"\"").append(docText(name)).append("\n\nGenerated by Automation.ai from test case events. ")
                .append("Review, validate and approve before executing.\n");
        if (description != null && !description.isBlank()) sb.append('\n').append(docText(description)).append('\n');
        sb.append("\"\"\"\n\nfrom automation_ai import Device\n\n\n");
        sb.append("def test_").append(identifier(name)).append("(device: Device):\n");
        if (events.isEmpty()) sb.append("    pass\n");
        int index = 1;
        for (TestCaseEvent e : events) {
            sb.append("    # ").append(index++).append(". ").append(comment(describe(e))).append('\n');
            double timeout = seconds(e.getTimeoutMs());
            switch (e.getAction()) {
                case DPAD_UP, DPAD_DOWN, DPAD_LEFT, DPAD_RIGHT, SELECT, BACK, HOME -> {
                    sb.append("    device.press(").append(py(e.getAction().name())).append(")\n");
                    sb.append("    device.sleep(").append(KEY_SETTLE_SECONDS).append(")\n");
                }
                case WAIT -> sb.append("    device.sleep(").append(Math.min(timeout, 30.0)).append(")\n");
                case SCREENSHOT -> sb.append("    device.screenshot(").append(py(nonBlank(e.getTarget(), "step_" + (index - 1)))).append(")\n");
                case ASSERT_TEXT_VISIBLE -> sb.append("    device.assert_text_visible(").append(py(e.getTarget()))
                        .append(", timeout=").append(timeout).append(")\n");
                case ASSERT_TEXT_NOT_VISIBLE -> sb.append("    device.assert_text_not_visible(").append(py(e.getTarget()))
                        .append(", timeout=").append(timeout).append(")\n");
                case ASSERT_ANY_TEXT_VISIBLE -> {
                    sb.append("    device.assert_any_text_visible([");
                    List<String> options = anyOptions(e.getTarget());
                    for (int i = 0; i < options.size(); i++) {
                        if (i > 0) sb.append(", ");
                        sb.append(py(options.get(i)));
                    }
                    sb.append("], timeout=").append(timeout).append(")\n");
                }
            }
        }
        return sb.toString();
    }

    /** Python double-quoted string literal. */
    static String py(String value) {
        StringBuilder sb = new StringBuilder("\"");
        for (char c : (value == null ? "" : value).toCharArray()) {
            switch (c) {
                case '\\' -> sb.append("\\\\");
                case '"' -> sb.append("\\\"");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20 || c == 0x7f) sb.append(String.format("\\x%02x", (int) c));
                    else sb.append(c);
                }
            }
        }
        return sb.append('"').toString();
    }

    static String identifier(String name) {
        String id = NON_IDENTIFIER.matcher((name == null ? "" : name).toLowerCase(Locale.ROOT)).replaceAll("_");
        id = id.replaceAll("^_+|_+$", "");
        if (id.isEmpty()) id = "case";
        return id.length() > 60 ? id.substring(0, 60) : id;
    }

    private static String docText(String s) {
        return CONTROL.matcher(s).replaceAll(" ").replace("\\", "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
    }

    // ── Robot Framework ─────────────────────────────────────────────────────

    static String robot(String name, String description, List<TestCaseEvent> events) {
        StringBuilder sb = new StringBuilder();
        sb.append("*** Settings ***\n");
        sb.append("Documentation    ").append(rb(name)).append(" - generated by Automation.ai from test case events. ")
                .append("Review, validate and approve before executing.\n");
        sb.append("Library    AutomationAiLibrary\n\n");
        sb.append("*** Test Cases ***\n").append(robotName(name)).append('\n');
        if (description != null && !description.isBlank()) sb.append("    [Documentation]    ").append(rb(description)).append('\n');
        if (events.isEmpty()) sb.append("    No Operation\n");
        int index = 1;
        for (TestCaseEvent e : events) {
            sb.append("    # ").append(index++).append(". ").append(comment(rb(describe(e)))).append('\n');
            String timeout = "timeout=" + seconds(e.getTimeoutMs());
            switch (e.getAction()) {
                case DPAD_UP, DPAD_DOWN, DPAD_LEFT, DPAD_RIGHT, SELECT, BACK, HOME -> {
                    sb.append("    Press Key    ").append(e.getAction().name()).append('\n');
                    sb.append("    Wait Seconds    ").append(KEY_SETTLE_SECONDS).append('\n');
                }
                case WAIT -> sb.append("    Wait Seconds    ").append(Math.min(seconds(e.getTimeoutMs()), 30.0)).append('\n');
                case SCREENSHOT -> sb.append("    Take Screenshot    ").append(rb(nonBlank(e.getTarget(), "step_" + (index - 1)))).append('\n');
                case ASSERT_TEXT_VISIBLE -> sb.append("    Text Should Be Visible    ").append(rb(e.getTarget())).append("    ").append(timeout).append('\n');
                case ASSERT_TEXT_NOT_VISIBLE -> sb.append("    Text Should Not Be Visible    ").append(rb(e.getTarget())).append("    ").append(timeout).append('\n');
                case ASSERT_ANY_TEXT_VISIBLE -> {
                    sb.append("    Any Text Should Be Visible");
                    for (String option : anyOptions(e.getTarget())) sb.append("    ").append(rb(option));
                    sb.append("    ").append(timeout).append('\n');
                }
            }
        }
        return sb.toString();
    }

    /** A single Robot argument: escapes variables, comments, named-argument '=', and collapses separators. */
    static String rb(String value) {
        String v = CONTROL.matcher(value == null ? "" : value).replaceAll(" ").strip().replaceAll(" {2,}", " ");
        if (v.isEmpty()) return "${EMPTY}";
        StringBuilder sb = new StringBuilder();
        for (char c : v.toCharArray()) {
            if (c == '\\' || c == '$' || c == '@' || c == '&' || c == '%' || c == '#' || c == '=') sb.append('\\');
            sb.append(c);
        }
        return sb.toString();
    }

    static String robotName(String name) {
        String n = ROBOT_NAME_UNSAFE.matcher(CONTROL.matcher(name == null ? "" : name).replaceAll(" ")).replaceAll(" ")
                .strip().replaceAll(" {2,}", " ");
        return n.isEmpty() ? "Generated Test" : n;
    }

    // ── Shared ──────────────────────────────────────────────────────────────

    static List<String> anyOptions(String target) {
        return java.util.Arrays.stream((target == null ? "" : target).split(Pattern.quote(TestCaseEvent.ANY_SEPARATOR.strip())))
                .map(String::strip).filter(s -> !s.isEmpty()).toList();
    }

    private static String describe(TestCaseEvent e) {
        StringBuilder sb = new StringBuilder(e.getAction().name());
        if (e.getTarget() != null && !e.getTarget().isBlank()) sb.append(" \"").append(e.getTarget()).append('"');
        if (e.getExpectedState() != null && !e.getExpectedState().isBlank()) sb.append(" - expected: ").append(e.getExpectedState());
        return sb.toString();
    }

    private static String comment(String text) {
        String c = CONTROL.matcher(text).replaceAll(" ");
        return c.length() > 200 ? c.substring(0, 200) + "..." : c;
    }

    private static double seconds(Integer timeoutMs) {
        int ms = timeoutMs == null ? 10_000 : timeoutMs;
        return Math.round(ms / 100.0) / 10.0;
    }

    private static String nonBlank(String value, String fallback) {
        return value == null || value.isBlank() ? fallback : value;
    }
}
